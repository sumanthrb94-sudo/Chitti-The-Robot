-- ─────────────────────────────────────────────────────────────
--  Chitti demo dataset — a fictional SaaS / hardware vendor.
--  Story arc baked in for fun queries:
--    • Top product overall: "Neon Atlas Mouse" (popular peripheral)
--    • Fastest-growing country: India ("IN") — heavy signups in last 4 mo
--    • Refund spike: "QuantumPad Pro" — a flagship that disappointed
--    • Plan mix: free dominates, pro is biggest revenue, enterprise rare
--    • Recent churn cluster on Pro users from BR
--  ~520 total rows (40 users, 20 products, 150 orders, ~310 items, 200 events).
--  Idempotent: INSERT OR IGNORE with explicit ids; CREATE TABLE IF NOT EXISTS.
-- ─────────────────────────────────────────────────────────────

CREATE TABLE IF NOT EXISTS _seed_meta (
  id INTEGER PRIMARY KEY CHECK (id = 1),
  seeded_at TEXT NOT NULL,
  version INTEGER NOT NULL
);

CREATE TABLE IF NOT EXISTS users (
  id INTEGER PRIMARY KEY,
  name TEXT NOT NULL,
  email TEXT UNIQUE NOT NULL,
  country TEXT,
  plan TEXT,
  signup_date TEXT
);

CREATE TABLE IF NOT EXISTS products (
  id INTEGER PRIMARY KEY,
  name TEXT,
  category TEXT,
  price REAL,
  sku TEXT UNIQUE
);

CREATE TABLE IF NOT EXISTS orders (
  id INTEGER PRIMARY KEY,
  user_id INTEGER,
  order_date TEXT,
  status TEXT,
  total REAL,
  FOREIGN KEY (user_id) REFERENCES users(id)
);

CREATE TABLE IF NOT EXISTS order_items (
  id INTEGER PRIMARY KEY,
  order_id INTEGER,
  product_id INTEGER,
  quantity INTEGER,
  unit_price REAL,
  FOREIGN KEY (order_id) REFERENCES orders(id),
  FOREIGN KEY (product_id) REFERENCES products(id)
);

CREATE TABLE IF NOT EXISTS events (
  id INTEGER PRIMARY KEY,
  user_id INTEGER,
  event_type TEXT,
  occurred_at TEXT,
  metadata TEXT,
  FOREIGN KEY (user_id) REFERENCES users(id)
);

